#!/usr/bin/env python3
"""Generate the files an app's own tooling reads: the Stylelint config and the agent skill.

    python3 -I build/app-tooling.py stylelint <classes.txt> <tokens.txt>  > sedna-ui.stylelintrc.json
    python3 -I build/app-tooling.py skill <CLAUDE.consuming-app.md>        > SKILL.md

Called by build/app-tooling.sh, which owns the paths and --check.

stylelint  The class list and the token list are build/css-inventory.sh's output for the
           shipped stylesheet, one name per line. Every class becomes one entry of
           selector-disallowed-list, so a rule in the app that names a class the library owns
           is reported; colour literals are reported everywhere except as the value of a token
           in brand.css, and brand.css may declare only tokens the library declares.

skill      The agent skill is the consuming-app CLAUDE.md block itself: the front matter, one
           paragraph saying what the two placeholders stand for, then every line of the doc
           after its first horizontal rule, unchanged.
"""
import json
import sys

COLOUR_FUNCTIONS = ["rgb", "rgba", "hsl", "hsla", "hwb", "lab", "lch", "oklab", "oklch", "color"]

OWNED = ("Selector \"%s\" names a class Sedna.UI owns. Set the component's token, use a variant the library ships, "
         "or put a class with this app's own prefix on the element.")
COLOUR = ("\"%s\" is a colour literal. Use a Sedna.UI token (var(--…)); a colour value belongs only in "
          "brand.css, as the value of a token the library declares.")
BRAND_COLOUR = ("\"%s: %s\" is a colour outside a token. In brand.css a colour is the value of a token "
                "Sedna.UI declares, and every other declaration reads one.")
BRAND_TOKEN = ("\"%s\" is no token Sedna.UI declares, and brand.css may only redefine one. Put a value of this app's own "
               "in another stylesheet, under this app's prefix (--<app>-…).")


def names(path):
    with open(path, encoding="utf-8") as f:
        return [line.strip() for line in f if line.strip()]


def stylelint(classes_path, tokens_path):
    classes = names(classes_path)
    tokens = [t[2:] for t in names(tokens_path)]
    config = {
        "$comment": "GENERATED by build/app-tooling.sh from the Sedna.UI stylesheet of the same version - do not edit. "
                    "Extend it from the app's own Stylelint config; see https://www.sedna-ui.com/tooling",
        "rules": {
            "selector-disallowed-list": [
                ["/\\." + c + "(?![\\w-])/" for c in classes],
                {"splitList": True, "message": OWNED},
            ],
            "color-no-hex": [True, {"message": COLOUR}],
            "color-named": ["never", {"message": COLOUR.replace('"%s" is', "A named colour is", 1)}],
            "function-disallowed-list": [COLOUR_FUNCTIONS, {"message": COLOUR}],
        },
        "overrides": [
            {
                "files": ["**/brand.css"],
                "rules": {
                    "color-no-hex": None,
                    "color-named": None,
                    "function-disallowed-list": None,
                    "declaration-property-value-disallowed-list": [
                        {"/^(?!--)/": ["/#[0-9a-fA-F]{3,8}\\b/",
                                       "/\\b(?:" + "|".join(COLOUR_FUNCTIONS) + ")\\(/i"]},
                        {"message": BRAND_COLOUR},
                    ],
                    "custom-property-pattern": [
                        "^(?:" + "|".join(tokens) + ")$",
                        {"message": BRAND_TOKEN},
                    ],
                },
            }
        ],
    }
    return json.dumps(config, indent=2, ensure_ascii=False) + "\n"


FRONT = """---
name: sedna-ui
description: How to build and change UI in an app that uses the Sedna.UI NuGet package - copy markup from the catalogue's MCP server, write CSS classes on plain HTML instead of components, change a component through its tokens, open dialogs through the presenters, and upgrade by the release notes. Use when writing or reviewing .razor, .html or .css in an app that references Sedna.UI.
---

<!-- GENERATED by build/app-tooling.sh from docs/CLAUDE.consuming-app.md - do not edit. -->

`<VERSION>` below is the `Sedna.UI` version in this app's project file (`<PackageReference Include="Sedna.UI" Version="…" />`).
`<APP-PREFIX>` is this app's own CSS prefix: read it from the app's `CLAUDE.md` or its stylesheets, and ask if neither names one.
"""


def skill(doc_path):
    with open(doc_path, encoding="utf-8") as f:
        lines = f.read().splitlines(keepends=True)
    try:
        rule = next(i for i, line in enumerate(lines) if line.rstrip("\n") == "---")
    except StopIteration:
        sys.exit(f"::error::{doc_path} has no '---' line: the skill is the block after it.")
    return FRONT + "".join(lines[rule + 1:])


def main(argv):
    if len(argv) == 3 and argv[0] == "stylelint":
        sys.stdout.write(stylelint(argv[1], argv[2]))
    elif len(argv) == 2 and argv[0] == "skill":
        sys.stdout.write(skill(argv[1]))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
