#!/usr/bin/env bash
#
# Generates wwwroot/tokens/Sedna.UI.tokens.json from the token parts in
# css-parts/ (00-04) plus the density remap in 90.
#
# Why a JSON export exists: the tokens are the design contract, and things outside
# CSS need to read it — a Figma import, a report generator picking chart colours, a
# native app matching the palette, a contrast audit. Today each of those would
# re-parse the stylesheet and guess.
#
# Why generated: the same reason the stylesheet is. A second copy of ~350 values is a
# second copy that goes stale, and a guard test fails the build when it does.
#
# No node and no npm package. Everything here is generated by shell and verified by
# dotnet; a JS toolchain to emit one JSON file would be the largest dependency in the
# project. Publishing to npm is separately out of scope — it needs a long-lived token,
# which breaks the no-stored-key posture.
#
# SHAPE: an ordered array of blocks, not a map of themes. Two reasons, both found by
# trying the map first:
#   * `:root` appears more than once — once at the top level and again inside
#     @media (prefers-contrast: more) — so a map keyed by selector produces duplicate
#     keys and silently loses one.
#   * The media condition is part of the contract. A consumer that ignores it would
#     apply the high-contrast palette unconditionally.
# Merging the blocks in order, honouring `media`, is exactly what a browser does.
#
# Usage:  build/export-tokens.sh          # regenerate
#         build/export-tokens.sh --check  # fail if out of date
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PARTS="$ROOT/src/Sedna.UI/css-parts"
OUT="$ROOT/src/Sedna.UI/wwwroot/tokens/Sedna.UI.tokens.json"

mkdir -p "$(dirname "$OUT")"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

# Emits TSV: media <TAB> selector <TAB> name <TAB> value.
# Bash does the JSON escaping, because awk doing both parsing and escaping is how a
# generator ends up emitting invalid JSON that nothing notices.
scan() {
    awk '
        function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }

        # Reset per file. A part is self-contained — no @media, block or comment spans
        # two of them — and without this the forced-colours media condition leaked into
        # 90-density.css, which is scanned after it and is not in any media query.
        FNR == 1 { media = ""; mediaDepth = 0; block = ""; inc = 0 }

        { line = $0 }

        # Strip comments, including ones spanning lines.
        inc { if (line ~ /\*\//) { sub(/^.*\*\//, "", line); inc = 0 } else next }
        { while (match(line, /\/\*.*\*\//)) sub(/\/\*.*\*\//, "", line)
          if (line ~ /\/\*/) { sub(/\/\*.*$/, "", line); inc = 1 } }

        # Track the enclosing @media, and the brace depth so its close is known.
        line ~ /^[[:space:]]*@media/ {
            media = line
            sub(/^[[:space:]]*@media[[:space:]]*/, "", media)
            sub(/[[:space:]]*\{.*$/, "", media)
            media = trim(media)
            mediaDepth = 1
            next
        }
        media != "" && line ~ /\{/ && line !~ /:root/ { mediaDepth++ }

        # A token block opens.
        line ~ /^[[:space:]]*:root[^{]*\{/ {
            sel = line
            sub(/[[:space:]]*\{.*$/, "", sel)
            block = trim(sel)
            next
        }
        block != "" && line ~ /^[[:space:]]*\}/ { block = ""; next }
        block == "" && media != "" && line ~ /^[[:space:]]*\}/ {
            if (--mediaDepth <= 0) media = ""
            next
        }

        # Declarations inside a token block. Split on ";" rather than taking the first
        # colon: several blocks put three related tokens on one line
        # (`--badge-cyan-bg: …; --badge-cyan-border: …; --badge-cyan-fg: …;`) and
        # reading one colon per line exported the first and mangled its value.
        block != "" && line ~ /--/ {
            count = split(line, decls, ";")
            for (d = 1; d <= count; d++) {
                one = trim(decls[d])
                if (one !~ /^--/) continue
                n = index(one, ":")
                if (n <= 0) continue
                name  = trim(substr(one, 1, n - 1))
                value = trim(substr(one, n + 1))
                printf "%s\t%s\t%s\t%s\n", media, block, name, value
            }
        }
    ' "$@"
}

# 0x = tokens and the theme blocks, 71 = the forced-colours remap (a theme block that
# happens to live with the appearance rules it needs), 90 = density.
RAW="$(scan "$PARTS"/0*.css "$PARTS"/71-forced-colors.css "$PARTS"/90-density.css)"

# JSON string escaping: backslash first, then quote. Nothing here contains a control
# character, and a tab would already have broken the TSV.
esc() { local s=${1//\\/\\\\}; printf '%s' "${s//\"/\\\"}"; }

{
    echo '{'
    echo '  "$comment": "GENERATED by build/export-tokens.sh from css-parts/. Do not edit.",'
    echo '  "name": "Sedna.UI",'
    echo '  "note": "Merge blocks in order. A block applies when its media condition matches and its selector matches the document root.",'
    echo '  "blocks": ['

    # Distinct (media, selector) pairs in first-appearance order.
    mapfile -t KEYS < <(printf '%s\n' "$RAW" | cut -f1,2 | awk '!seen[$0]++')

    for ki in "${!KEYS[@]}"; do
        media="${KEYS[$ki]%%$'\t'*}"
        selector="${KEYS[$ki]#*$'\t'}"

        printf '    {\n'
        if [[ -n "$media" ]]; then
            printf '      "media": "%s",\n' "$(esc "$media")"
        else
            printf '      "media": null,\n'
        fi
        printf '      "selector": "%s",\n' "$(esc "$selector")"
        printf '      "tokens": {\n'

        mapfile -t LINES < <(printf '%s\n' "$RAW" \
            | awk -F'\t' -v m="$media" -v s="$selector" '$1 == m && $2 == s')
        for li in "${!LINES[@]}"; do
            name="$(printf '%s' "${LINES[$li]}" | cut -f3)"
            value="$(printf '%s' "${LINES[$li]}" | cut -f4)"
            comma=','; [[ $li -eq $(( ${#LINES[@]} - 1 )) ]] && comma=''
            printf '        "%s": "%s"%s\n' "$(esc "$name")" "$(esc "$value")" "$comma"
        done

        printf '      }\n'
        comma=','; [[ $ki -eq $(( ${#KEYS[@]} - 1 )) ]] && comma=''
        printf '    }%s\n' "$comma"
    done

    echo '  ]'
    echo '}'
} > "$TMP"

if [[ "${1:-}" == "--check" ]]; then
    if cmp -s "$TMP" "$OUT"; then
        echo "ok      token export is up to date"
        exit 0
    fi
    echo "::error::$OUT does not match css-parts/. Run build/export-tokens.sh"
    diff "$OUT" "$TMP" | head -30 || true
    exit 1
fi

cp "$TMP" "$OUT"
echo "wrote   $(basename "$OUT")"
